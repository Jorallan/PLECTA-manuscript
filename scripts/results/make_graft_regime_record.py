"""Build the record for the comparison run on GraFT's own generator.

The manuscript's comparator table is measured on one procedural generator --
ours -- which PLECTA was developed against. This record carries the answer to
the obvious objection: the same three methods, on scenes generated by GraFT's
own vendored generator at GraFT's own published settings, across a density
ladder that spans their published range and continues into ours.

Two metric families are carried, because they disagree and the disagreement is
the point:

  * the manuscript's own common-fragment pairwise family, which scores whether
    fragments that belong together are grouped together;
  * GraFT's own instance family from its Fig. 2 -- filament matched coverage
    and filament coverage -- computed with the same implementation used
    elsewhere in this project, in GraFT's own density bins.

Neither is presented as correcting the other. They measure different things,
and a method can be first on one and last on the other.

Source study: C:/Repos/comparisons/graft_regime, whose PROTOCOL.md was fixed
before any scene existed and whose MEMO.md records a reference bug found and
corrected during the run.

Usage:
  python scripts/results/make_graft_regime_record.py
"""
from __future__ import annotations

import csv
import hashlib
import json
import statistics as st
from collections import defaultdict
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
RESULTS = REPO / "results"
STUDY = Path("C:/Repos/comparisons/graft_regime")
PAIRWISE = STUDY / "results" / "per_scene_all.csv"
OWN = STUDY / "results" / "graft_own_metric.csv"

METHODS = ("plecta", "graft", "graft_native", "dnai")
DISPLAY = {"plecta": "PLECTA", "graft": "GraFT",
           "graft_native": "GraFT own front end", "dnai": "DNAi"}
METRICS = ("f1", "precision", "recall", "fragment_recovery_recovery_rate",
           "adjusted_rand_index", "vi_split_bits", "vi_merge_bits")


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def mean(values):
    values = [v for v in values if v == v]          # drop NaN
    return float(st.mean(values)) if values else None


def main() -> None:
    pairwise = list(csv.DictReader(PAIRWISE.open(encoding="utf-8")))
    own = list(csv.DictReader(OWN.open(encoding="utf-8")))

    strata = sorted({int(r["n_lines"]) for r in pairwise})
    by_stratum = []
    for n in strata:
        rows = [r for r in pairwise if int(r["n_lines"]) == n]
        entry = {
            "n_lines": n,
            "n_scenes": len({r["scene"] for r in rows}),
            "density_mean": mean(float(r["density"]) for r in rows
                                 if r["method"] == "plecta"),
            "methods": {},
        }
        for m in METHODS:
            sub = [r for r in rows if r["method"] == m and r["status"] == "ok"]
            own_sub = [r for r in own
                       if int(r["n_lines"]) == n and r["method"] == m]
            entry["methods"][m] = {
                "n_scored": len(sub),
                "n_censored": len([r for r in rows if r["method"] == m]) - len(sub),
                **{k: mean(float(r[k]) for r in sub) for k in METRICS},
                "filament_matched_coverage": mean(float(r["fmc"]) for r in own_sub),
                "filament_coverage": mean(float(r["filament_coverage"])
                                          for r in own_sub),
                "n_instances_emitted": mean(float(r["n_pred"]) for r in own_sub),
                "n_instances_true": mean(float(r["n_gt"]) for r in sub),
                "seconds_per_scene": mean(float(r["seconds"]) for r in sub
                                          if r["seconds"] not in ("", "nan")),
            }
        by_stratum.append(entry)

    overall = {}
    for m in METHODS:
        sub = [r for r in pairwise if r["method"] == m and r["status"] == "ok"]
        own_sub = [r for r in own if r["method"] == m]
        overall[m] = {
            "n_scored": len(sub),
            **{k: mean(float(r[k]) for r in sub) for k in METRICS},
            "filament_matched_coverage": mean(float(r["fmc"]) for r in own_sub),
            "filament_coverage": mean(float(r["filament_coverage"])
                                      for r in own_sub),
        }

    payload = {
        "role": ("three methods on GraFT's own generator, at GraFT's own "
                 "published settings; a supplementary regime, not the paper's "
                 "main claim"),
        "generator": ("GraFT dataUtils.generate_filamentous_structure, "
                      "vendored and unmodified; box 500, curvature 10, "
                      "additive Gaussian noise variance 0.01"),
        "stratifier": "number of generated lines, as in GraFT's own Fig. 2",
        "published_range_note": ("GraFT's Fig. 2 spans an image density of 0 to "
                                 "about 0.02 centreline px per image px; the 5 "
                                 "to 40 line strata reproduce that range and the "
                                 "60 to 130 strata continue into the density of "
                                 "this manuscript's own scenes"),
        "metric_families": {
            "pairwise": ("eval/core/common_metric.py, the manuscript's own "
                         "endpoint; scores whether fragments that belong "
                         "together are grouped together"),
            "graft_own": ("filament matched coverage and filament coverage from "
                          "GraFT's Fig. 2; both derive from one bipartite "
                          "whole-filament to whole-detection matching, so "
                          "neither can see which arms were joined at a "
                          "crossing"),
        },
        "source_record": {
            "study": str(STUDY).replace("\\", "/"),
            "protocol": "PROTOCOL.md",
            "memo": "MEMO.md",
            "pairwise_csv": {"file": "results/per_scene_all.csv",
                             "sha256": sha256(PAIRWISE)},
            "graft_own_csv": {"file": "results/graft_own_metric.csv",
                              "sha256": sha256(OWN)},
        },
        "overall": overall,
        "by_stratum": by_stratum,
    }

    destination = RESULTS / "plecta_graft_regime.json"
    destination.write_text(json.dumps(payload, indent=2) + "\n",
                           encoding="utf-8")
    print("wrote", destination)
    print("\n%6s %9s  %s" % ("lines", "density",
                             "  ".join("%26s" % DISPLAY[m] for m in METHODS)))
    print("%6s %9s  %s" % ("", "", "  ".join("%26s" % "pairwise F1 / matched cov"
                                             for _ in METHODS)))
    for e in by_stratum:
        cells = []
        for m in METHODS:
            b = e["methods"][m]
            #  GraFT's own-front-end arm has no entry in the GraFT-metric
            #  csv, which covers the three arms scored on the shared mask, so
            #  its matched coverage is absent rather than zero.
            cov = b["filament_matched_coverage"]
            cells.append("%26s" % ("%.3f / %s"
                                   % (b["f1"],
                                      "--" if cov is None else "%.3f" % cov)))
        print("%6d %9.4f  %s" % (e["n_lines"], e["density_mean"], "  ".join(cells)))


if __name__ == "__main__":
    main()
