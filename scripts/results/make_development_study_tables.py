"""Generate supplementary tables for the development-only redesign studies."""
from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any, Mapping, Sequence


CELL_LABELS = (
    ("skeleton_minimum_turn", "Skeleton fragments + minimum-turn"),
    ("skeleton_filaseg_gates", "Skeleton fragments + FilaSeg gates"),
    ("hough_minimum_turn", "Hough fragments + minimum-turn"),
    ("hough_filaseg_gates", "Hough fragments + FilaSeg gates"),
)
CONTRAST_LABELS = (
    (
        "filaseg_gate_effect_with_skeleton_fragments",
        "Gate effect with skeleton fragments",
    ),
    (
        "filaseg_gate_effect_with_hough_fragments",
        "Gate effect with Hough fragments",
    ),
    (
        "hough_source_effect_under_minimum_turn",
        "Hough-source effect under minimum-turn",
    ),
    (
        "hough_source_effect_under_filaseg_gates",
        "Hough-source effect under FilaSeg gates",
    ),
    (
        "fragment_source_by_grouper_interaction",
        "Source-by-grouper interaction",
    ),
)


def _load(path: Path) -> dict[str, Any]:
    data = json.loads(path.read_text(encoding="utf-8"))
    if not isinstance(data, dict):
        raise ValueError(f"JSON root is not an object: {path}")
    return data


def _estimate(stat: Mapping[str, Any]) -> str:
    return (
        rf"\shortstack{{{float(stat['mean']):.3f}\\"
        rf"{{[{float(stat['ci_lo']):.3f}, {float(stat['ci_hi']):.3f}]}}}}"
    )


def _hybrid_table(report: Mapping[str, Any]) -> str:
    aggregate = report["aggregate"]
    lines = [
        "% Generated by make_development_study_tables.py. Do not edit.",
        r"\begin{tabular}{lr}",
        r"\toprule",
        r"Cell or paired contrast & Common-fragment $F_1$ \\",
        r"\midrule",
    ]
    for key, label in CELL_LABELS:
        lines.append(f"{label} & {_estimate(aggregate['by_cell'][key]['f1'])} \\\\")
    lines.append(r"\midrule")
    for key, label in CONTRAST_LABELS:
        lines.append(f"{label} & {_estimate(aggregate['contrasts'][key]['f1'])} \\\\")
    lines.extend([r"\bottomrule", r"\end{tabular}", ""])
    return "\n".join(lines)


def _empirical_by_density_seed(
    report: Mapping[str, Any],
) -> dict[float, dict[int, Mapping[str, Any]]] | None:
    """One representative empirical row per (density, seed).

    ``empirical_stage3_per_scene`` (merged into the paper-repo copy of this
    report; see ``scripts/figures/fig_factorial_density_width.py`` and the
    2026-07-30 empirical-arm run) carries 3 width-level rows per (seed,
    density) cell. The structural negative control already establishes that
    those 3 rows are numerically identical for every performance metric (max
    within-geometry range 0.0 -- see ``empirical_stage3_width_negative_control``),
    so density-level aggregates below are computed over the 4 independent
    seeds only, picking one arbitrary (lowest-width) row per seed rather than
    triple-counting non-independent width replicates.
    """
    rows = report.get("empirical_stage3_per_scene")
    if not rows:
        return None
    by_density: dict[float, dict[int, Mapping[str, Any]]] = {}
    for row in rows:
        density = float(row["target_length_density_px_per_px2"])
        seed = int(row["seed"])
        by_seed = by_density.setdefault(density, {})
        current = by_seed.get(seed)
        if current is None or float(row["bundle_width_level_px"]) < float(
            current["bundle_width_level_px"]
        ):
            by_seed[seed] = row
    return by_density


def _mean(values: Sequence[float]) -> float:
    return sum(values) / len(values)


def _factorial_table(report: Mapping[str, Any]) -> str:
    cells = report["factorial_cells"]
    grouped: dict[float, dict[float, Mapping[str, Any]]] = {}
    for cell in cells:
        grouped.setdefault(
            float(cell["target_length_density_px_per_px2"]), {}
        )[float(cell["bundle_width_level_px"])] = cell
    empirical = _empirical_by_density_seed(report)
    has_empirical = empirical is not None
    n_cols = 11 if has_empirical else 7
    lines = [
        "% Generated by make_development_study_tables.py. Do not edit.",
        # 11 numeric columns overrun the A4 text block at footnotesize with the
        # default 6pt inter-column padding. Both the type size and the padding
        # are reduced so the table fits; scoped by the surrounding brace group.
        r"{\scriptsize" if n_cols == 11 else r"{\footnotesize",
        r"\setlength{\tabcolsep}{2.2pt}",
        rf"\begin{{tabular}}{{{'r' * n_cols}}}",
        r"\toprule",
    ]
    if has_empirical:
        lines += [
            r"\shortstack{Target\\density} & "
            r"\shortstack{Achieved\\density} & "
            r"\shortstack{Crossings\\per Mpx} & "
            r"\shortstack{Mean gap\\count} & "
            r"\multicolumn{3}{c}{Thick-mask coverage by width} & "
            r"\shortstack{Common\\$F_1$} & "
            r"\shortstack{Pairwise\\$P$} & "
            r"\shortstack{Pairwise\\$R$} & "
            r"\shortstack{Object\\recovery} \\",
            r"\cmidrule(lr){5-7}",
            r" & & & & 6 px & 11 px & 16 px & "
            r"\multicolumn{4}{c}{(pooled over widths; width-invariant, n=4 seeds)} \\",
            r"\cmidrule(lr){8-11}",
        ]
    else:
        lines += [
            r"\shortstack{Target length\\density} & "
            r"\shortstack{Achieved length\\density} & "
            r"\shortstack{Crossings\\per Mpx} & "
            r"\shortstack{Mean gap\\count} & "
            r"\multicolumn{3}{c}{Thick-mask coverage by width} \\",
            r"\cmidrule(lr){5-7}",
            r" & & & & 6 px & 11 px & 16 px \\",
        ]
    lines.append(r"\midrule")
    for target, width_cells in sorted(grouped.items()):
        reference = width_cells[min(width_cells)]
        metrics = reference["metrics"]
        thick = [
            width_cells[width]["metrics"]["achieved_thick_mask_coverage"]["mean"]
            for width in (6.0, 11.0, 16.0)
        ]
        row = (
            f"{target:.3f} & "
            f"{metrics['achieved_length_density_px_per_px2']['mean']:.4f} & "
            f"{metrics['crossing_density_per_megapixel']['mean']:.1f} & "
            f"{metrics['gap_count']['mean']:.1f} & "
            f"{thick[0]:.3f} & {thick[1]:.3f} & {thick[2]:.3f}"
        )
        if has_empirical:
            by_seed = empirical[target]
            f1 = _mean([float(r["common_f1"]) for r in by_seed.values()])
            precision = _mean([float(r["common_precision"]) for r in by_seed.values()])
            recall = _mean([float(r["common_recall"]) for r in by_seed.values()])
            recovery = _mean(
                [float(r["fragment_recovery"]["recovery_rate"]) for r in by_seed.values()]
            )
            row += f" & {f1:.3f} & {precision:.3f} & {recall:.3f} & {recovery:.3f}"
        lines.append(row + r" \\")
    if has_empirical:
        lines.append(r"\midrule")
        lines.append(
            # A left-aligned multicolumn cannot line-break, so this long note
            # produced a hugely overfull row. A p-column wraps it to the text
            # block instead.
            rf"\multicolumn{{{n_cols}}}{{@{{}}p{{0.97\linewidth}}@{{}}}}"
            r"{\itshape Development-only, "
            r"exploratory evidence (36 synthetic scenes: 3 length-density "
            r"levels $\times$ 3 true bundle-width levels $\times$ 4 seeds). "
            r"Common-fragment $F_1$/$P$/$R$/object recovery: FilaSeg "
            r"Stage-3 (pre-render) centreline output vs.\ overlap-aware "
            r"centreline ground truth; exactly width-invariant within every "
            r"(seed, density) block (max.\ range across widths $=0.0$); "
            r"pooled over widths, averaged over 4 seeds.} \\"
        )
    lines.append(r"\bottomrule")
    lines.append(r"\end{tabular}")
    lines.append(r"}")
    lines.append("")
    return "\n".join(lines)


def build(
    hybrid_json: Path,
    factorial_json: Path,
    out_dir: Path,
) -> dict[str, Any]:
    hybrid = _load(hybrid_json)
    factorial = _load(factorial_json)
    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / "development_hybrid_table.tex").write_text(
        _hybrid_table(hybrid), encoding="utf-8"
    )
    (out_dir / "development_factorial_table.tex").write_text(
        _factorial_table(factorial), encoding="utf-8"
    )
    summary = {
        "schema_version": 1,
        "hybrid_report": str(hybrid_json),
        "factorial_report": str(factorial_json),
        "hybrid_report_sha256": _sha256(hybrid_json),
        "factorial_report_sha256": _sha256(factorial_json),
        "hybrid_aggregate": hybrid["aggregate"],
        "factorial_validation": factorial["validation"],
        "factorial_cells": factorial["factorial_cells"],
    }
    (out_dir / "development_study_summary.json").write_text(
        json.dumps(summary, indent=2) + "\n", encoding="utf-8"
    )
    return summary


def _sha256(path: Path) -> str:
    import hashlib

    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for block in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--hybrid-json", type=Path, required=True)
    parser.add_argument("--factorial-json", type=Path, required=True)
    parser.add_argument("--out-dir", type=Path, required=True)
    args = parser.parse_args(argv)
    build(args.hybrid_json, args.factorial_json, args.out_dir)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
